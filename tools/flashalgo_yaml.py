#!/usr/bin/env python3
"""Generate the Soul Injector target.yaml pieces for a flashalgo ELF.

    flashalgo_yaml.py algo.elf [--name NAME]   # flash_algorithms: entry + self_tests:
    flashalgo_yaml.py algo.elf --tests-only    # just self_tests:

Everything comes from the ELF that the library laid out:
  PrgCode           -> instructions (base64) and load_address
  Init, UnInit, ... -> pc_* offsets from load_address (Thumb bit included, as target-gen does)
  FlashDevice       -> flash_properties (CMSIS FlashOS.h layout)
  .flashalgo_tests  -> self_tests (generated by reflection from [[=flashalgo::test]] members)

Standard library only, so it runs anywhere Python 3.8+ does.
"""

import argparse
import base64
import struct
import sys

ENTRY_POINTS = [
    # (symbol, yaml key)
    ("Init", "pc_init"),
    ("UnInit", "pc_uninit"),
    ("ProgramPage", "pc_program_page"),
    ("EraseSector", "pc_erase_sector"),
    ("EraseChip", "pc_erase_all"),
    ("Verify", "pc_verify"),
    ("BlankCheck", "pc_blank_check"),
    ("ReadFlash", "pc_read"),
]

TEST_KIND_BUFFER = 1


class Elf:
    """Just enough ELF32/ELF64 parsing: section headers and the symbol table."""

    def __init__(self, path):
        with open(path, "rb") as f:
            self.data = f.read()
        if self.data[:4] != b"\x7fELF":
            raise SystemExit(f"{path}: not an ELF file")
        self.is64 = self.data[4] == 2
        self.endian = "<" if self.data[5] == 1 else ">"

        if self.is64:
            shoff, = self._unpack("Q", 0x28)
            shentsize, shnum, shstrndx = self._unpack("HHH", 0x3A)
        else:
            shoff, = self._unpack("I", 0x20)
            shentsize, shnum, shstrndx = self._unpack("HHH", 0x2E)

        self.sections = []
        for i in range(shnum):
            off = shoff + i * shentsize
            if self.is64:
                name, stype, _flags, addr, offset, size, link = self._unpack("IIQQQQI", off)
            else:
                name, stype, _flags, addr, offset, size, link = self._unpack("IIIIIII", off)
            self.sections.append({"name_off": name, "type": stype, "addr": addr, "offset": offset, "size": size, "link": link})

        strtab = self.sections[shstrndx]
        for s in self.sections:
            s["name"] = self._cstr(strtab["offset"] + s["name_off"])

    def _unpack(self, fmt, off):
        return struct.unpack_from(self.endian + fmt, self.data, off)

    def _cstr(self, off):
        end = self.data.index(b"\0", off)
        return self.data[off:end].decode()

    def section(self, name):
        for s in self.sections:
            if s["name"] == name:
                return s
        return None

    def section_bytes(self, s):
        if s["type"] == 8:  # SHT_NOBITS
            return bytes(s["size"])
        return self.data[s["offset"]:s["offset"] + s["size"]]

    def symbols(self):
        """name -> value, for the global symbols in .symtab."""
        symtab = next((s for s in self.sections if s["type"] == 2), None)  # SHT_SYMTAB
        if symtab is None:
            return {}
        strtab = self.sections[symtab["link"]]
        entsize = 24 if self.is64 else 16
        result = {}
        for i in range(symtab["size"] // entsize):
            off = symtab["offset"] + i * entsize
            if self.is64:
                name, info, _other, _shndx, value, _size = self._unpack("IBBHQQ", off)
            else:
                name, value, _size, info, _other, _shndx = self._unpack("IIIBBH", off)
            if info >> 4 == 1:  # STB_GLOBAL
                result[self._cstr(strtab["offset"] + name)] = value
        return result

    def read_at_address(self, addr, size):
        """Bytes at a virtual address, from whichever allocated section contains it."""
        for s in self.sections:
            if s["addr"] and s["addr"] <= addr and addr + size <= s["addr"] + s["size"]:
                return self.section_bytes(s)[addr - s["addr"]:addr - s["addr"] + size]
        return None


def parse_tests(elf):
    sec = elf.section(".flashalgo_tests")
    if sec is None:
        raise SystemExit("no .flashalgo_tests section: was the algorithm built with FLASHALGO_EXPORT?")
    raw = elf.section_bytes(sec)
    magic, version, count, record_size, _ = struct.unpack_from(elf.endian + "4sHHHH", raw, 0)
    if magic != b"FATS" or version != 1:
        raise SystemExit(f"unexpected test table header {magic!r} v{version}")

    tests = []
    for i in range(count):
        off = 12 + i * record_size
        test_id, kind = struct.unpack_from(elf.endian + "IB", raw, off)
        name = raw[off + 8:off + 40].split(b"\0", 1)[0].decode()
        tests.append({"id": test_id, "kind": kind, "name": name})
    return tests


def parse_flash_device(elf, symbols):
    sec = elf.section("DeviceData")
    raw = elf.section_bytes(sec) if sec else None
    if raw is None and "FlashDevice" in symbols:
        raw = elf.read_at_address(symbols["FlashDevice"], 160)
    if raw is None:
        raise SystemExit("no FlashDevice / DeviceData in the ELF")

    e = elf.endian
    dev = {
        "name": raw[2:130].split(b"\0", 1)[0].decode(),
        "dev_addr": struct.unpack_from(e + "I", raw, 132)[0],
        "device_size": struct.unpack_from(e + "I", raw, 136)[0],
        "page_size": struct.unpack_from(e + "I", raw, 140)[0],
        "empty": raw[148],
        "program_timeout": struct.unpack_from(e + "I", raw, 152)[0],
        "erase_timeout": struct.unpack_from(e + "I", raw, 156)[0],
        "sectors": [],
    }
    off = 160
    while off + 8 <= len(raw):
        size, address = struct.unpack_from(e + "II", raw, off)
        if size == 0xFFFFFFFF and address == 0xFFFFFFFF:
            break
        dev["sectors"].append((size, address))
        off += 8
    return dev


def yaml_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def self_tests_yaml(tests):
    lines = ["self_tests:"]
    for t in tests:
        lines.append(f"  - name: {yaml_str(t['name'])}")
        lines.append("    type: simple")
        lines.append(f"    addr: 0x{t['id']:08x}")
        if t["kind"] == TEST_KIND_BUFFER:
            lines[-1] += "  # takes a RAM buffer (r1 = size, r2 = pointer)"
    return "\n".join(lines)


def algorithm_yaml(elf, name, core):
    symbols = elf.symbols()
    prg = elf.section("PrgCode")
    if prg is None:
        raise SystemExit("no PrgCode section: link with ld/flashalgo.ld (flashalgo_add_algorithm in CMake)")

    load = prg["addr"]
    blob = elf.section_bytes(prg)
    dev = parse_flash_device(elf, symbols)

    lines = [
        "flash_algorithms:",
        f"  - name: {yaml_str(name)}",
        f"    description: {yaml_str(dev['name'])}",
        "    default: true",
        f"    instructions: {base64.b64encode(blob).decode()}",
        f"    load_address: 0x{load:08x}",
    ]
    for sym, key in ENTRY_POINTS:
        if sym in symbols:
            lines.append(f"    {key}: 0x{symbols[sym] - load:x}")
        elif sym in ("Init", "UnInit", "ProgramPage", "EraseSector"):
            raise SystemExit(f"required entry point {sym} is missing from the ELF")
    # Everything (data and bss included) is in PrgCode and nothing is R9-relative, so the
    # static base only has to point at valid RAM: use the end of the image.
    lines.append(f"    data_section_offset: 0x{(load + len(blob) + 3) & ~3:08x}")
    lines += [
        "    flash_properties:",
        "      address_range:",
        f"        start: 0x{dev['dev_addr']:x}",
        f"        end: 0x{dev['dev_addr'] + dev['device_size']:x}",
        f"      page_size: 0x{dev['page_size']:x}",
        f"      erased_byte_value: 0x{dev['empty']:x}",
        f"      program_page_timeout: {dev['program_timeout']}",
        f"      erase_sector_timeout: {dev['erase_timeout']}",
        "      sectors:",
    ]
    for size, address in dev["sectors"]:
        lines.append(f"        - size: 0x{size:x}")
        lines.append(f"          address: 0x{address:x}")
    lines += ["    cores:", f"      - {core}"]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("elf", help="algorithm ELF built with flashalgo")
    ap.add_argument("--name", default="algorithm", help="flash algorithm name (default: algorithm)")
    ap.add_argument("--core", default="main", help="core name for the algorithm entry (default: main)")
    ap.add_argument("--tests-only", action="store_true", help="only print the self_tests: list")
    args = ap.parse_args()

    elf = Elf(args.elf)
    tests = parse_tests(elf)
    if args.tests_only:
        print(self_tests_yaml(tests))
        return 0

    print(algorithm_yaml(elf, args.name, args.core))
    if tests:
        print()
        print(self_tests_yaml(tests))
    return 0


if __name__ == "__main__":
    sys.exit(main())
